// endpoint — куда отправлять форму (например, Formspree/Buttondown/свой воркер):
//   NEXT_PUBLIC_REVIEW_ENDPOINT=https://formspree.io/f/xxxxxxx  npm run build
// Если переменная не задана — форма не делает сетевых запросов, а собирает
// готовое письмо: кнопка «Отправить письмом» (mailto) + копирование текста.
export const REVIEW_SETTINGS = {
  // Если задать NEXT_PUBLIC_REVIEW_ENDPOINT — отзыв уходит POST-запросом и публикуется сам.
  endpoint: process.env.NEXT_PUBLIC_REVIEW_ENDPOINT ?? '',
  // Адрес владельца для подсказки «куда прислать». Пусто = подсказка не показывается,
  // а посетитель просто копирует готовый текст отзыва и отправляет через /contact.
  email: '',
};

// Книги, по которым можно фильтровать отзывы. slug совпадает с src/lib/products.ts,
// поэтому здесь намеренно нет импорта каталога (этот файл попадает в клиентский бандл).
export const REVIEW_BOOKS: { slug: string; label: Record<Locale, string> }[] = [
  { slug: 'ffl-acquisition-disposition-120', label: { en: 'A&D Book — 120 pages', ru: 'Журнал A&D — 120 страниц' } },
  { slug: 'ffl-acquisition-disposition-200', label: { en: 'A&D Book — 200 pages', ru: 'Журнал A&D — 200 страниц' } },
  { slug: 'firearms-dealer-ad-log-landscape', label: { en: 'A&D Log — landscape', ru: 'Журнал A&D — альбомный' } },
];

/** Человекочитаемое название книги по slug (или undefined, если slug неизвестен). */
export function bookTitle(slug: string | undefined, locale: Locale): string | undefined {
  if (!slug) return undefined;
  const found = REVIEW_BOOKS.find((b) => b.slug === slug);
  return found ? found.label[locale] : undefined;
}
