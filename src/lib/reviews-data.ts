import { type Locale } from '@/src/i18n/settings';

// ============================================================================
// ОТЗЫВЫ — ДАННЫЕ (единственный источник правды)
// ============================================================================
// Сайт статический: бэкенда нет. Отзывы — это обычный массив ниже.
// Пока он пуст (REVIEWS = []), и это НЕ баг: страница показывает красивое
// пустое состояние с призывом оставить первый отзыв.
//
// --- КАК ДОБАВИТЬ НАСТОЯЩИЙ ОТЗЫВ (без логина и без базы данных) ------------
// 1. Получите отзыв: через форму на /reviews/ (кнопка «Оставить отзыв»),
//    по email владельца (REVIEW_SETTINGS.email) или из письма покупателя.
// 2. Скопируйте объект-шаблон, вставьте его В НАЧАЛО массива REVIEWS
//    (свежие сверху) и заполните поля:
//
//    {
//      id: 'r-2026-09-23-001',            // уникальный; дата + порядковый номер
//      name: 'Daniel R.',                  // как подписался автор отзыва
//      location: 'Reno, NV',               // необязательно
//      rating: 5,                          // 1 | 2 | 3 | 4 | 5
//      title: 'Exactly the layout I needed', // необязательно
//      body: 'Полный текст отзыва, 20–1500 символов, без HTML.',
//      bookSlug: 'ffl-acquisition-disposition-120', // необязательно, см. REVIEW_BOOKS
//      date: '2026-09-23',                 // ISO-дата (YYYY-MM-DD)
//      verified: true,                     // true только если покупка подтверждена
//      photos: ['https://.../photo-1.jpg'],// необязательно, прямые ссылки на картинки
//      helpful: 3,                         // сколько людей отметили «полезно» ВНЕ сайта
//      reply: {                            // необязательный ответ владельца
//        text: 'Спасибо, что написали. ...',
//        date: '2026-09-24',
//      },
//    },
//
// 3. Проведите правку через git и задеплойте сайт — отзывы появятся при сборке.
//
// ВАЖНО О ЧЕСТНОСТИ ДАННЫХ:
// - Не выдумывайте отзывы, имена, города и цифру «полезно».
// - verified: true ставьте ТОЛЬКО когда покупка реально подтверждена
//   (номер заказа Amazon или письмо покупателя).
// - Если отзыв переведён с другого языка — так и напишите в тексте.
// ----------------------------------------------------------------------------

export type StarRating = 1 | 2 | 3 | 4 | 5;

export type ReviewReply = {
  /** Текст ответа владельца. Без HTML. */
  text: string;
  /** ISO-дата ответа (YYYY-MM-DD). */
  date: string;
};

export type Review = {
  id: string;
  name: string;
  location?: string;
  rating: 1 | 2 | 3 | 4 | 5;
  title?: string;
  body: string;
  bookSlug?: string;
  /** ISO-дата отзыва (YYYY-MM-DD). */
  date: string;
  /** Проверенная покупка — только при реальном подтверждении. */
  verified?: boolean;
  /** Прямые ссылки (https) на фото покупателя. */
  photos?: string[];
  /** Голоса «полезно», накопленные вне сайта. */
  helpful?: number;
  /** Ответ владельца/автора, если он был. */
  reply?: ReviewReply;
};

/** Заполненный пользователем черновик отзыва (до валидации/отправки). */
export type ReviewSubmission = {
  name: string;
  location?: string;
  rating: StarRating;
  title?: string;
  body: string;
  bookSlug?: string;
  photoUrl?: string;
};

// ---------------------------------------------------------------------------
